#!/usr/bin/env python3
"""Tables for the Results section, from the scored full run.

    python scripts/results_tables.py [--run full]

Writes results/<run>/RESULTS_tables.md. Everything is computed from scores*.csv and item_scores*.csv;
nothing is typed in by hand. Unit of analysis: the question (repetitions and models are averaged
within a question first; 95% intervals from 5,000 bootstrap resamples of the 22 questions).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from nis2eval.analysis import boot_ci  # noqa: E402

CORE = ["qwen3.5-397b", "qwen3.8-27b", "gemma-4-31b-it", "deepseek-v4-flash"]
EXTRA = ["gemma-4-26b-a4b-it"]
JUDGE_MAIN, JUDGE_2 = "qwen3.8-27b", "gemma-4-31b-it"
CONDS = ["C0", "C1", "C2"]
NAMES = {"C0": "C0 question only", "C1": "C1 with the decree-law", "C2": "C2 with the directive instead"}
ROWS = [("coverage", "Checklist coverage", "pct"),
        ("fab_any", "Answers with at least one unsupported claim", "pct"),
        ("fab_claims", "Unsupported claims per answer", "num"),
        ("juris_confusion", "Answers with jurisdiction confusion", "pct"),
        ("flag_rate", "Uncertain items properly flagged", "pct"),
        ("overconf_rate", "Uncertain items stated as certain (of those addressed)", "pct"),
        ("admits_gap", "Says the decree does not settle the point (3 such questions)", "pct"),
        ("flags_mismatch", "Says the text given is not the Portuguese law", "pct")]


def fmt(m, lo, hi, kind):
    if np.isnan(m):
        return "n/a"
    if kind == "pct":
        return f"{100 * m:.0f}%" + ("" if np.isnan(lo) else f" [{100 * lo:.0f}, {100 * hi:.0f}]")
    return f"{m:.2f}" + ("" if np.isnan(lo) else f" [{lo:.2f}, {hi:.2f}]")


def pooled(df: pd.DataFrame, metric: str, cond: str):
    """Mean over questions of (mean over models of (mean over repetitions))."""
    d = df[df["condition"] == cond]
    per_q = d.groupby(["qid", "model"])[metric].mean().groupby("qid").mean()
    return boot_ci(per_q.to_numpy())


def pooled_table(df: pd.DataFrame) -> list[str]:
    md = ["| | " + " | ".join(NAMES[c] for c in CONDS) + " |", "|---|" + "---|" * len(CONDS)]
    for metric, label, kind in ROWS:
        cells = []
        for c in CONDS:
            m, lo, hi, _n = pooled(df, metric, c)
            cells.append(fmt(m, lo, hi, kind))
        md.append(f"| {label} | " + " | ".join(cells) + " |")
    return md


def per_model(df: pd.DataFrame, metric: str, kind: str) -> list[str]:
    md = ["| Model | " + " | ".join(CONDS) + " |", "|---|" + "---|" * len(CONDS)]
    for m in [x for x in CORE + EXTRA if x in set(df["model"])]:
        cells = []
        for c in CONDS:
            v = df[(df["model"] == m) & (df["condition"] == c)].groupby("qid")[metric].mean()
            cells.append(fmt(*boot_ci(v.to_numpy())[:3], kind))
        md.append(f"| {m} | " + " | ".join(cells) + " |")
    return md


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="full")
    a = ap.parse_args()
    run = ROOT / "results" / a.run
    S = {JUDGE_MAIN: pd.read_csv(run / "scores.csv")}
    I = {JUDGE_MAIN: pd.read_csv(run / "item_scores.csv")}
    if (run / f"scores.{JUDGE_2}.csv").exists():
        S[JUDGE_2] = pd.read_csv(run / f"scores.{JUDGE_2}.csv")
        I[JUDGE_2] = pd.read_csv(run / f"item_scores.{JUDGE_2}.csv")
    for k in S:
        S[k] = S[k][S[k]["condition"].isin(CONDS)]
        I[k] = I[k][I[k]["condition"].isin(CONDS)]
    main_models = [m for m in CORE if m != JUDGE_MAIN]
    df = S[JUDGE_MAIN]
    core = df[df["model"].isin(CORE)]
    mainset = df[df["model"].isin(main_models)]
    md = [f"# Results tables (run `{a.run}`)", "",
          "Generated by `scripts/results_tables.py`. Percentages are means over the 22 questions "
          "(models and repetitions averaged within a question first), with 95% bootstrap intervals over questions.", ""]

    md += [f"## 1. Main result: {len(main_models)} models, judge {JUDGE_MAIN} (the judge's own answers left out)", "",
           f"Models: {', '.join(main_models)}. {len(mainset)} answers.", ""] + pooled_table(mainset) + [""]
    md += [f"## 2. Same, all four core models (judge {JUDGE_MAIN}, including its own answers)", "",
           f"{len(core)} answers.", ""] + pooled_table(core) + [""]
    if JUDGE_2 in S:
        d2 = S[JUDGE_2]
        m2 = [m for m in CORE if m != JUDGE_2]
        both_out = [m for m in CORE if m not in (JUDGE_MAIN, JUDGE_2)]
        md += [f"## 3. Second judge: {JUDGE_2}, its own answers left out", "",
               f"Models: {', '.join(m2)}. {len(d2[d2['model'].isin(m2)])} answers.", ""] + pooled_table(d2[d2["model"].isin(m2)]) + [""]
        md += [f"## 4. The two models that are neither judge ({', '.join(both_out)}), under each judge", ""]
        for j in (JUDGE_MAIN, JUDGE_2):
            md += [f"**Judge {j}**", ""] + pooled_table(S[j][S[j]["model"].isin(both_out)]) + [""]

    md += ["## 5. Per model (judge " + JUDGE_MAIN + ")", "", "**Checklist coverage**", ""] + per_model(df, "coverage", "pct")
    md += ["", "**Answers with at least one unsupported claim**", ""] + per_model(df, "fab_any", "pct")
    md += ["", "**Answers with jurisdiction confusion**", ""] + per_model(df, "juris_confusion", "pct") + [""]

    # uncertain items: raw counts, because rates on the few addressed items are fragile
    it = I[JUDGE_MAIN]
    it = it[it["model"].isin(main_models) & (it["status"] != "verified")]
    md += ["## 6. Uncertain items (status inferred or to confirm): what the answers did with them", "",
           f"Counts of item marks, {len(main_models)} main models, judge {JUDGE_MAIN}. 11 uncertain items in 9 questions.", "",
           "| Condition | Marks | Not addressed | Stated as certain | Flagged | Hedged without reason |", "|---|---|---|---|---|---|"]
    for c in CONDS:
        v = it[it["condition"] == c]["uncertainty"].value_counts()
        n = int(v.sum())
        g = lambda k: f"{int(v.get(k, 0))} ({100 * v.get(k, 0) / n:.0f}%)" if n else "0"
        md.append(f"| {c} | {n} | {g('not_addressed')} | {g('stated_as_certain')} | {g('flagged')} | {g('hedged_without_reason')} |")
    md += ["", "By item, condition C1 only:", "", "| Item | Status | Stated as certain | Flagged | Not addressed |", "|---|---|---|---|---|"]
    c1 = it[it["condition"] == "C1"]
    for (qid, item, status), g in c1.groupby(["qid", "item", "status"]):
        v = g["uncertainty"].value_counts()
        md.append(f"| {qid} {item} | {status} | {int(v.get('stated_as_certain', 0))} | {int(v.get('flagged', 0))} | {int(v.get('not_addressed', 0))} |")
    md.append("")

    # citations: counts, by what the citation was attributed to
    md += ["## 7. Citations (deterministic check, no judge)", "",
           f"All four core models, {len(core)} answers. A citation is checked against the decree-law when the answer attributes it "
           "to the decree-law, and against the directive when it attributes it to the directive.", "",
           "| Condition | Answers | Citations per answer | Checked against the decree-law | of which do not exist | "
           "Checked against the directive | of which do not exist | To other instruments |", "|---|---|---|---|---|---|---|---|"]
    for c in CONDS:
        v = core[core["condition"] == c]
        chk, inv, dr, dinv = v["cit_checked"].sum(), v["cit_invalid"].sum(), v["cit_directive"].sum(), v["cit_directive_invalid"].sum()
        md.append(f"| {c} | {len(v)} | {v['cit_total'].mean():.1f} | {int(chk)} | {int(inv)} ({100 * inv / chk:.1f}%) | "
                  f"{int(dr)} | {int(dinv)} ({100 * dinv / dr:.1f}%) | {int(v['cit_other'].sum())} |" if chk and dr else
                  f"| {c} | {len(v)} | {v['cit_total'].mean():.1f} | {int(chk)} | {int(inv)} | {int(dr)} | {int(dinv)} | {int(v['cit_other'].sum())} |")
    md.append("")

    # which national law the answers rest on
    import json
    import re as _re
    ans = {}
    for line in (run / "answers.jsonl").read_text(encoding="utf-8").splitlines():
        try:
            rec = json.loads(line)
        except json.JSONDecodeError:
            continue
        if rec.get("status") == "ok":
            ans[rec["key"]] = rec
    keys = set(core["key"])
    names = _re.compile(r"125/2025")
    old_law = _re.compile(r"46/2018|65/2021")
    other = _re.compile(r"(Decreto-Lei|Lei)\s+n\.?\s?[ºo°]?\.?\s*(?!125/2025)\d+(?:-[A-Z])?/202[3-6]", _re.I)
    md += ["## 7b. Which national law the answers rest on (text search, no judge)", "",
           f"All four core models. The decree-law repeals Lei n.º 46/2018 and Decreto-Lei n.º 65/2021.", "",
           "| Condition | Answers | Name Decreto-Lei n.º 125/2025 | Cite the repealed regime (Lei 46/2018 or DL 65/2021) | "
           "Name another statute dated 2023 to 2026 |", "|---|---|---|---|---|"]
    for c in CONDS:
        v = [a for k, a in ans.items() if k in keys and a["condition"] == c]
        n = len(v)
        f = lambda rx: f"{sum(1 for a in v if rx.search(a['answer']))} ({100 * sum(1 for a in v if rx.search(a['answer'])) / n:.0f}%)"
        md.append(f"| {c} | {n} | {f(names)} | {f(old_law)} | {f(other)} |")
    md.append("")

    # the three questions the decree does not answer
    md += ["## 8. The three questions the decree-law does not answer (L2-10, L2-11, L2-12)", "",
           f"Share of answers that say the decree does not settle the point; {len(main_models)} main models.", "",
           "| Question | " + " | ".join(CONDS) + " |", "|---|" + "---|" * len(CONDS)]
    sil = mainset[mainset["decree_silent"] == 1]
    for qid, g in sil.groupby("qid"):
        md.append(f"| {qid} | " + " | ".join(f"{100 * g[g['condition'] == c]['admits_gap'].mean():.0f}% ({len(g[g['condition'] == c])})" for c in CONDS) + " |")
    md += ["", "Unsupported claims on these three questions:", "", "| | " + " | ".join(CONDS) + " |", "|---|" + "---|" * len(CONDS),
           "| Answers with at least one unsupported claim | " + " | ".join(f"{100 * sil[sil['condition'] == c]['fab_any'].mean():.0f}%" for c in CONDS) + " |", ""]

    # spread between repetitions
    sd = core.groupby(["model", "condition", "qid"])["coverage"].std().groupby("condition").mean()
    md += ["## 9. Spread between repetitions", "",
           "Mean standard deviation of coverage across the 3 repetitions of a cell (model x question): "
           + ", ".join(f"{c} {sd[c]:.2f}" for c in CONDS) + ".", ""]

    if any(m in set(df["model"]) for m in EXTRA):
        ex = df[df["model"].isin(EXTRA)]
        md += ["## 10. Supplementary model(s): " + ", ".join(EXTRA), "",
               f"{len(ex)} answers graded so far (target 198 per model).", ""] + pooled_table(ex) + [""]
    (run / "RESULTS_tables.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
