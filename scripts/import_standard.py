#!/usr/bin/env python3
"""Build data/standard/standard.json from Bia's standard JSON.

Usage: python scripts/import_standard.py [--source PATH] [--frozen] [--dry-run]

Her file is the source of truth for the questions (Portuguese and English), the checklist items,
the statuses, the citations with their evidence excerpts, and the grading notes. This script only
renames fields to the schema the code uses and prints what changed against the standard already
in place, so nothing is retyped by hand.

  her field                       ours
  checklist                       items
  item_en / item_pt               text_en / text_pt
  status_en (status)              status (status_pt)
  type == not_answered_by_law     decree_silent = true
  part anexo / decreto            source regime / decreto
  grading_notes_en                grading_note
  differs_from_directive.claim_en decree_vs_directive
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# the file the author sent on 14 Nov with her decisions of 15 Nov applied (scripts/apply_revision_2026_11_15.py)
SOURCE = ROOT / "data" / "standard" / "source" / "standard-2026-11-15.json"
TARGET = ROOT / "data" / "standard" / "standard.json"

STATUS = {"verificado": "verified", "inferido": "inferred", "a confirmar": "to confirm", "proposta": "proposal"}


def _letters(point: str | None):
    """'a) a c)' -> (['a','b','c'], None); 'c) e d)' -> (['c','d'], None); 'b) i)' -> (['b'], 'i')."""
    if not point:
        return [], None
    p = point.strip()
    m = re.fullmatch(r"([a-z])\) a ([a-z])\)", p)
    if m:
        return [chr(c) for c in range(ord(m.group(1)), ord(m.group(2)) + 1)], None
    m = re.fullmatch(r"([a-z])\) e ([a-z])\)", p)
    if m:
        return [m.group(1), m.group(2)], None
    m = re.fullmatch(r"([a-z])\) ([ivx]+)\)", p)
    if m:
        return [m.group(1)], m.group(2)
    m = re.fullmatch(r"([a-z])\)", p)
    if m:
        return [m.group(1)], None
    raise ValueError(f"point not understood: {point!r}")


def _citation(c: dict) -> dict:
    article = int(re.fullmatch(r"(\d+)\.º", c["article"]).group(1))
    paragraphs = [int(c["paragraph"])] if c.get("paragraph") else []
    points, subpoint = _letters(c.get("point"))
    raw = f"art. {article}.º"
    if paragraphs:
        raw += f", n.º {paragraphs[0]}"
    if c.get("point"):
        raw += f", al. {c['point']}"
    if c["part"] == "decreto":
        raw += ", do decreto"
    return {"raw": raw, "source": {"anexo": "regime", "decreto": "decreto"}[c["part"]], "article": article,
            "paragraphs": paragraphs, "points": points, "subpoint": subpoint, "page": c["pdf_page"],
            "evidence": c["evidence"]}


def convert(src: dict, frozen: bool) -> dict:
    out_q = []
    for q in src["questions"]:
        items = []
        for it in q["checklist"]:
            assert it["id"].startswith(q["id"] + "-"), it["id"]
            assert STATUS[it["status"]] == it["status_en"], it["id"]
            cits = [_citation(c) for c in it["citations"]]
            raw = "; ".join(f"{c['raw']}, p. {c['page']}" for c in cits) or "Text search of the whole decree"
            items.append({"id": it["id"][len(q["id"]) + 1:], "text_en": it["item_en"], "text_pt": it["item_pt"],
                          "citations": cits, "citation_raw": raw, "status": it["status_en"],
                          "status_pt": it["status"]})
        dfd = q.get("differs_from_directive") or {}
        out_q.append({
            "id": q["id"], "batch": int(q["id"][1]), "type": q["type"],
            "question_en": q["question_en"], "question_pt": q["question_pt"],
            "decree_silent": q["type"] == "not_answered_by_law", "items": items,
            "decree_vs_directive": dfd.get("claim_en", ""),
            "decree_vs_directive_status": dfd.get("status_en", ""),
            "grading_note": q.get("grading_notes_en", ""),
        })
    m = src.get("meta", {})
    meta = {
        "title": "NIS2 (PT) compliance-advice reference standard",
        "reference_law": "Decreto-Lei n.º 125/2025, de 4 de dezembro (decree-law and annexed Regime Jurídico da Cibersegurança)",
        "version": ("frozen " if frozen else "draft, NOT FROZEN, ") + m.get("date", ""),
        "revision": m.get("revision", ""),
        "provenance": "Generated by scripts/import_standard.py from data/standard/source/"
                      + SOURCE.name + " (written by Bia). Do not edit by hand: edit the source and re-run.",
        "citation_convention": "source 'regime' = article of the annexed regime (arts. 1-87); 'decreto' = article "
                               "of the decree-law itself (arts. 1-11). 'evidence' is a literal excerpt of the "
                               "decree on the cited page.",
        "statuses": {
            "verified": "Checked in the official text, with article, paragraph, point and PDF page.",
            "inferred": "Our conclusion from official or public texts that they do not state expressly.",
            "to confirm": "Depends on company facts, on regulation or texts not read, or comes from a secondary source.",
            "proposal": "Our recommendation, not a statement about the law.",
        },
        "decree_silent": "true = the decree-law itself does not give the answer (source type 'not_answered_by_law').",
        "decree_vs_directive_note": "The directive side of each difference was marked 'to confirm' in the source.",
    }
    return {"meta": meta, "questions": out_q}


def diff(old: dict, new: dict) -> list[str]:
    """What the new standard changes against the one in place (the one the pilot ran on)."""
    lines = []
    oq = {q["id"]: q for q in old["questions"]}
    for q in new["questions"]:
        o = oq.get(q["id"])
        if o is None:
            lines.append(f"{q['id']}: new question")
            continue
        for f in ("question_pt", "question_en", "decree_silent", "grading_note", "decree_vs_directive"):
            if (o.get(f) or "") != (q.get(f) or ""):
                lines.append(f"{q['id']}: {f} changed\n    was: {o.get(f)}\n    now: {q.get(f)}")
        oi = {it["id"]: it for it in o["items"]}
        for it in q["items"]:
            p = oi.get(it["id"])
            if p is None:
                lines.append(f"{q['id']}-{it['id']}: new item")
                continue
            for f in ("text_en", "status"):
                if p.get(f) != it.get(f):
                    lines.append(f"{q['id']}-{it['id']}: {f} changed\n    was: {p.get(f)}\n    now: {it.get(f)}")
            key = lambda c: (c["source"], c["article"], tuple(c["paragraphs"]), tuple(c["points"]), c["subpoint"], c["page"])
            if [key(c) for c in p["citations"]] != [key(c) for c in it["citations"]]:
                lines.append(f"{q['id']}-{it['id']}: citations changed\n    was: {p['citation_raw']}\n    now: {it['citation_raw']}")
        for iid in oi.keys() - {it["id"] for it in q["items"]}:
            lines.append(f"{q['id']}-{iid}: item removed")
    for qid in oq.keys() - {q["id"] for q in new["questions"]}:
        lines.append(f"{qid}: question removed")
    return lines


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, default=SOURCE)
    ap.add_argument("--frozen", action="store_true", help="mark the version as frozen (only after Bia says so)")
    ap.add_argument("--dry-run", action="store_true", help="print the differences, write nothing")
    a = ap.parse_args()
    new = convert(json.loads(a.source.read_text(encoding="utf-8")), a.frozen)
    if TARGET.exists():
        changes = diff(json.loads(TARGET.read_text(encoding="utf-8")), new)
        print(f"{len(changes)} difference(s) against the standard in place:")
        for c in changes:
            print(" -", c)
    n_items = sum(len(q["items"]) for q in new["questions"])
    n_cit = sum(len(it["citations"]) for q in new["questions"] for it in q["items"])
    print(f"{len(new['questions'])} questions, {n_items} items, {n_cit} citations; version: {new['meta']['version']}")
    if not a.dry_run:
        TARGET.write_text(json.dumps(new, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print("wrote", TARGET.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
